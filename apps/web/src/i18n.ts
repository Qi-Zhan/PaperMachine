function detectLocale(): Locale {
  if (typeof window !== 'undefined') {
    const saved = window.localStorage.getItem('papermachine.locale')
    if (saved === 'en' || saved === 'zh-CN') return saved
  }
  if (typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('zh')) return 'zh-CN'
  return 'en'
}

function expandMessages(source: Record<string, string>): MessageTree {
  const result: MessageTree = {}
  for (const [path, value] of Object.entries(source)) {
    const segments = path.split('.')
    let target = result
    for (const segment of segments.slice(0, -1)) {
      const child = target[segment]
      if (typeof child === 'object') {
        target = child
      } else {
        const next: MessageTree = {}
        target[segment] = next
        target = next
      }
    }
    target[segments.at(-1)!] = value
  }
  return result
}

function syncDocumentLocale(next: Locale) {
  if (typeof document !== 'undefined') document.documentElement.lang = next
}

const i18nOptions = {
  legacy: false,
  locale: detectLocale(),
  fallbackLocale: 'en',
  messages: {
    en: expandMessages(english),
    'zh-CN': expandMessages(chinese),
  },
} as const

export const i18n = createI18n<MessageTree, Locale, false>(i18nOptions)

syncDocumentLocale(i18n.global.locale.value as Locale)

export function t(key: MessageKey, params: Params = {}): string {
  return i18n.global.t(key, params)
}

export function setLocale(next: Locale) {
  i18n.global.locale.value = next
  syncDocumentLocale(next)
  if (typeof window !== 'undefined') window.localStorage.setItem('papermachine.locale', next)
}

export function currentLocale(): Locale {
  return i18n.global.locale.value as Locale
}

export function statusText(status: string): string {
  const translated = statuses[currentLocale()][status]
  if (translated) return translated
  const text = status.replaceAll('_', ' ')
  return text.charAt(0).toUpperCase() + text.slice(1)
}

export function useAppI18n() {
  const composer = useI18n({ useScope: 'global' })
  return {
    locale: composer.locale,
    setLocale,
    t,
  }
}
